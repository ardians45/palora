export const fixName = (code, name) => NAME_FIXES[code]?.name || name;

// ---------------------------------------------------------------------------
// Warna: di data impor lama, 341 barang kolom warnanya berisi nama lengkap (mis. "SS - 800 Green").
// Ambil kata warna di akhir nama; kalau tidak ada kata warna yang jelas, kosongkan (lebih baik kosong daripada salah).
// ---------------------------------------------------------------------------
const COLOR_WORDS = new Set(
  (
    'merah hijau biru kuning putih hitam coklat cokelat orange oranye pink ungu abu abu-abu grey gray clear bening transparan transp trans ' +
    'red green blue yellow black white brown purple peach magenta violet navy cream krem silver gold emas metalik metallic met ' +
    'dark dk light muda tua smoke tosca toska maroon salem lime'
  ).split(' ')
);

export function colorFromName(name) {
  const words = String(name || '')
    .replace(/[()]/g, ' ')
    .trim()
    .split(/\s+/);
  const tail = [];
  for (let i = words.length - 1; i >= 0; i--) {
    const w = words[i].toLowerCase().replace(/[^a-z-]/g, '');
    if (w && COLOR_WORDS.has(w)) tail.unshift(words[i]);
    else break;
  }
  return tail.join(' ');
}

/** Warna yang benar untuk satu barang: perbaiki hanya bila kolom warna = nama lengkap. */
export function fixColor(name, color) {
  if (!color || color.trim() !== String(name || '').trim()) return color || '';
  return colorFromName(name);
}
